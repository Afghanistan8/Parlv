#!/usr/bin/env node
/**
 * Advisory adversarial review for a Parlv steward.
 *
 * This is a convenience, not a substitute for the test suite. It re-derives, from
 * the repository source, a handful of the guarantees Parlv claims, so a reviewer
 * can spot drift quickly:
 *
 *   1. the contract carries the exact pinned Studionet header;
 *   2. every @gl.public.write calls _guard_chain() before it does anything;
 *   3. the contract's get_actions keys and the app's Acts type are identical;
 *   4. there is no pause / upgrade / owner / admin / operator surface;
 *   5. committed text carries no model or assistant attribution.
 *
 * Hard failures exit non-zero. Advisories are printed and do not fail the run.
 *
 * Usage
 *   node tools/adversarial_review.mjs
 */

import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CONTRACT = join(ROOT, "contracts", "parlv.py");
const TYPES = join(ROOT, "web", "lib", "types.ts");

const EXPECTED_HEADER = [
  "# v0.2.16",
  '# { "Depends": "py-genlayer:132536jbnxkd1axfxg5rpfr5b60cr11adm2y4r90hgn0l59qsp9w" }',
];

const SKIP_DIRS = new Set([
  ".git", "node_modules", ".next", "dist", "artifacts", "__pycache__",
  ".pytest_cache", "coverage", "proofs",
]);
const TEXT_EXT = new Set([
  ".py", ".md", ".ts", ".tsx", ".mjs", ".js", ".json", ".toml", ".ini", ".txt", ".yml", ".yaml",
]);
const ATTRIBUTION = /(claude|anthropic|opencode|open-code|cursor|copilot|chatgpt|co-authored-by|generated by|as an ai|language model)/i;

const failures = [];
const advisories = [];
const passes = [];

function fail(message) {
  failures.push(message);
}
function advise(message) {
  advisories.push(message);
}
function pass(message) {
  passes.push(message);
}

function read(path) {
  return readFileSync(path, "utf8");
}

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const info = statSync(full);
    if (info.isDirectory()) {
      if (SKIP_DIRS.has(entry)) continue;
      walk(full, out);
    } else {
      out.push(full);
    }
  }
  return out;
}

/** 1. Pinned header. */
function checkHeader(source) {
  const lines = source.split("\n");
  if (lines[0] !== EXPECTED_HEADER[0] || lines[1] !== EXPECTED_HEADER[1]) {
    fail(`contract header is not the pinned Studionet header\n  expected:\n${EXPECTED_HEADER.join("\n")}`);
  } else {
    pass("pinned Studionet header (v0.2.16 + proven runner)");
  }
  if (/(^|\n)# .*:(test|latest)\b/.test(source.slice(0, 300))) {
    fail("runner alias :test/:latest present in the header (rejected in non-debug mode)");
  }
}

/** 2. Every write guards the chain first. */
function checkWritesGuardChain(source) {
  const lines = source.split("\n");
  const writes = [];
  for (let i = 0; i < lines.length; i += 1) {
    if (/^    @gl\.public\.write(?:\.payable)?\s*$/.test(lines[i])) {
      let j = i + 1;
      while (j < lines.length && !/^    def /.test(lines[j])) j += 1;
      if (j >= lines.length) continue;
      const name = /^    def (\w+)\(/.exec(lines[j])?.[1] ?? "(unknown)";
      let k = j + 1;
      while (k < lines.length && !/^    (def |@)/.test(lines[k])) k += 1;
      const body = lines.slice(j + 1, k);
      const guardAt = body.findIndex((l) => /^\s+_guard_chain\(\)/.test(l));
      writes.push({ name, guardAt, line: j + 1 });
    }
  }
  if (writes.length === 0) fail("no @gl.public.write methods found");
  const unguarded = writes.filter((w) => w.guardAt === -1);
  if (unguarded.length) {
    fail(`writes without _guard_chain(): ${unguarded.map((w) => w.name).join(", ")}`);
  } else {
    pass(`every write guards the chain (${writes.length} writes)`);
  }
  const late = writes.filter((w) => w.guardAt > 1);
  if (late.length) {
    advise(
      `_guard_chain() is not the first statement in: ` +
        late.map((w) => `${w.name} (line ${w.line}, offset ${w.guardAt})`).join(", "),
    );
  }
}

/** 3. Action-key parity between the contract and the app. */
function checkGateParity(contractSource) {
  const returnMatch = /return \{"role": role,.*?\}/s.exec(contractSource);
  if (!returnMatch) {
    fail("could not find the get_actions return dict");
    return;
  }
  const contractKeys = new Set([...returnMatch[0].matchAll(/"(\w+)"\s*:/g)].map((m) => m[1]));

  const types = read(TYPES);
  const actsMatch = /export interface Acts \{(.*?)\}/s.exec(types);
  if (!actsMatch) {
    fail("could not find the Acts interface in web/lib/types.ts");
    return;
  }
  const appKeys = new Set([...actsMatch[1].matchAll(/^\s*([A-Za-z_]\w*):/gm)].map((m) => m[1]));

  const onlyContract = [...contractKeys].filter((k) => !appKeys.has(k));
  const onlyApp = [...appKeys].filter((k) => !contractKeys.has(k));
  if (onlyContract.length || onlyApp.length) {
    fail(
      `get_actions keys and Acts type drifted\n  contract only: ${onlyContract.join(", ") || "-"}\n` +
        `  app only: ${onlyApp.join(", ") || "-"}`,
    );
  } else {
    pass(`contract and app action keys match (${contractKeys.size} gates)`);
  }
}

/** 4. No governance surface. */
function checkNoGovernanceSurface(source) {
  const forbiddenDefs = /^\s*def\s+(pause|unpause|upgrade|set_owner|transfer_ownership|grant_role|revoke_role|set_admin|set_operator|destroy|selfdestruct|delegate)\b/im;
  const found = forbiddenDefs.exec(source);
  if (found) {
    fail(`forbidden governance method found: ${found[1]}`);
  } else {
    pass("no pause/upgrade/owner/admin/operator method");
  }

  const stored = [...source.matchAll(/^\s*self\.(owner|admin|operator|upgrader|pauser)\s*[:=]/gim)].map(
    (m) => m[1],
  );
  if (stored.length) {
    fail(`a stored governance key is declared: ${stored.join(", ")}`);
  } else {
    pass("no stored owner/admin/operator/upgrade key");
  }

  if (/def\s+get_governance\b/.test(source)) {
    pass("get_governance view is present (auditable on chain)");
  } else {
    advise("no get_governance view; 'no governance' is not readable on chain");
  }
}

/** 5. No model/assistant attribution in committed text. */
function checkAttribution(files) {
  const self = fileURLToPath(import.meta.url);
  const hits = [];
  for (const file of files) {
    if (resolve(file) === resolve(self)) continue; // this script names the patterns
    const ext = file.slice(file.lastIndexOf("."));
    if (!TEXT_EXT.has(ext)) continue;
    // The probe/ tree is a captured third-party reference, not authored text.
    if (relative(ROOT, file).startsWith(`probe${"\\"}`) || relative(ROOT, file).startsWith("probe/")) {
      continue;
    }
    let text;
    try {
      text = readFileSync(file, "utf8");
    } catch {
      continue;
    }
    const lines = text.split("\n");
    lines.forEach((line, i) => {
      if (ATTRIBUTION.test(line)) hits.push(`${relative(ROOT, file)}:${i + 1}: ${line.trim()}`);
    });
  }
  if (hits.length) {
    advise(`possible attribution found (${hits.length}):\n  ${hits.join("\n  ")}`);
  } else {
    pass("no model/assistant attribution in authored text");
  }
}

function main() {
  let contractSource;
  try {
    contractSource = read(CONTRACT);
  } catch {
    fail(`cannot read ${CONTRACT}`);
    report();
    return;
  }

  checkHeader(contractSource);
  checkWritesGuardChain(contractSource);
  checkGateParity(contractSource);
  checkNoGovernanceSurface(contractSource);
  checkAttribution(walk(ROOT));

  report();
}

function report() {
  process.stdout.write("\nParlv adversarial review\n");
  for (const p of passes) process.stdout.write(`  ok    ${p}\n`);
  for (const a of advisories) process.stdout.write(`  warn  ${a}\n`);
  for (const f of failures) process.stdout.write(`  FAIL  ${f}\n`);
  process.stdout.write(
    `\n${passes.length} passed, ${advisories.length} advisory, ${failures.length} failed\n`,
  );
  process.exit(failures.length ? 1 : 0);
}

main();
